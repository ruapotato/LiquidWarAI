"""Transfer evaluation: does a policy trained on the density sim still play the real
game well?

The opponent here is the actual Liquid War 6 kernel -- `liblw6ker` compiled from
source and called through ctypes -- not a re-implementation of it. The density sim is
a smooth approximation, which it has to be to be differentiable, so transfer is
measured rather than assumed.

Both sides play the same generated maps, injected into the kernel, so the only
difference between the two columns is the physics.

Games run in worker processes with the policy on CPU: LW6's fighter update is
sequential and order-dependent, so a game cannot be batched, and the per-game cost is
dominated by the kernel rather than by the ~90k-parameter net.
"""
from __future__ import annotations

import argparse
import json
import multiprocessing as mp
from pathlib import Path

import numpy as np
import torch

from ..config import load
from ..policy.agents import SCRIPTED, NetAgent
from ..policy.net import CursorPolicy
from ..lw6.env import LW6Env
from ..sim.maps import make_maps, spawn_points
from .arena import head_to_head


def _scenario(cfg, seed):
    """One map, generated by the same code the density sim uses."""
    gen = torch.Generator(device="cpu").manual_seed(seed)
    return make_maps(1, cfg, "cpu", gen)[0].numpy()


def _play_one(args):
    spec_a, spec_b, cfg, seed, episode_len, _fighters, swap = args
    walls = _scenario(cfg, seed)
    env = LW6Env(width=int(cfg.sim.W), height=int(cfg.sim.H), device="cpu", walls=walls,
                 max_cursor_speed=float(cfg.sim.MAX_CURSOR_SPEED))
    a = _build(spec_a, cfg)
    b = _build(spec_b, cfg)
    ta, tb = (1, 0) if swap else (0, 1)
    with torch.no_grad():
        for _ in range(episode_len):
            act_a = a.act(env, ta)
            act_b = b.act(env, tb)
            action = (torch.stack([act_b, act_a], 1) if swap
                      else torch.stack([act_a, act_b], 1))
            env.step(action)
    s = float(env.score()[0])
    env.close()
    return 1.0 - s if swap else s


def _build(spec, cfg, device="cpu"):
    """Agents are named by string, not passed as objects, because each worker process
    rebuilds its own on CPU."""
    if spec in SCRIPTED:
        return SCRIPTED[spec]
    net = CursorPolicy(cfg).to(device)
    net.load_state_dict(torch.load(spec, map_location=device))
    net.eval()
    return NetAgent(net, name=Path(spec).stem)


def head_to_head_reference(spec_a, spec_b, cfg, *, games=16, episode_len=400,
                           fighters=150, processes=None):
    """Same contract as arena.head_to_head, played inside the verbatim LW6 port.

    Agents are named by string (a scripted name or a checkpoint path) rather than
    passed as objects, because each worker process rebuilds its own on CPU.
    """
    jobs = [(spec_a, spec_b, cfg, s, episode_len, fighters, s % 2 == 1)
            for s in range(games)]
    with mp.Pool(processes or min(mp.cpu_count(), games)) as pool:
        scores = pool.map(_play_one, jobs)
    s = np.array(scores)
    eps = 1e-3
    win = (s > 0.5 + eps).astype(float)
    draw = (np.abs(s - 0.5) <= eps).astype(float)
    return dict(win_rate=float(win.mean()), draw_rate=float(draw.mean()),
                loss_rate=float(1 - win.mean() - draw.mean()),
                mean_share=float(s.mean()), games=games)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="default.yaml")
    ap.add_argument("--policy", required=True, help="path to a saved policy, or a scripted name")
    ap.add_argument("--against", default="hold_own")
    ap.add_argument("--games", type=int, default=16)
    ap.add_argument("--episode-len", type=int, default=400)
    ap.add_argument("--fighters", type=int, default=150)
    ap.add_argument("--size", type=int, default=48)
    a = ap.parse_args()
    cfg = load(a.config, **{"sim.H": a.size, "sim.W": a.size})
    ref = head_to_head_reference(a.policy, a.against, cfg, games=a.games,
                                 episode_len=a.episode_len, fighters=a.fighters)
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    dens = head_to_head(_build(a.policy, cfg, dev), SCRIPTED[a.against], cfg,
                        games=a.games, episode_len=a.episode_len, device=dev)
    out = {"real_lw6": ref, "density_sim": dens,
           "transfer_gap_mean_share": ref["mean_share"] - dens["mean_share"]}
    print(json.dumps(out, indent=2))
    return out


if __name__ == "__main__":
    main()
